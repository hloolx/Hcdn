// Generates packages/ui/src/charts/world-dots.ts: land points on a lon/lat grid
// (equirectangular), encoded compactly. Run with: node scripts/gen-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(new URL("../packages/ui/package.json", import.meta.url));
const { geoContains } = require("d3-geo");
const { feature } = require("topojson-client");
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const STEP = 1.6; // degrees
const cols = Math.round(360 / STEP);
const rows = Math.round(150 / STEP); // lat 80N .. 70S
const hits = [];
for (let r = 0; r < rows; r++) {
  const lat = 80 - r * STEP;
  for (let c = 0; c < cols; c++) {
    const lon = -180 + c * STEP;
    if (geoContains(land, [lon, lat])) hits.push(r * cols + c);
  }
}
// delta + base36 encoding keeps the file small
let prev = 0;
const enc = hits.map((h) => { const d = h - prev; prev = h; return d.toString(36); }).join(",");
const out = `// Generated by web/scripts/gen-dots.mjs from world-atlas land-110m (public domain data).
// Land dots on a ${STEP}° lon/lat grid; ${hits.length} points.
export const DOT_STEP = ${STEP};
export const DOT_COLS = ${cols};
export const DOT_TOP_LAT = 80;
const ENCODED = "${enc}";

let cache: [number, number][] | null = null;
/** [lon, lat] of every land dot. */
export function worldDots(): [number, number][] {
  if (cache) return cache;
  const out: [number, number][] = [];
  let idx = 0;
  for (const part of ENCODED.split(",")) {
    idx += parseInt(part, 36);
    const r = Math.floor(idx / DOT_COLS);
    const c = idx % DOT_COLS;
    out.push([-180 + c * DOT_STEP, DOT_TOP_LAT - r * DOT_STEP]);
  }
  cache = out;
  return out;
}
`;
writeFileSync(new URL("../packages/ui/src/charts/world-dots.ts", import.meta.url), out);
console.log("points:", hits.length, "bytes:", out.length);
